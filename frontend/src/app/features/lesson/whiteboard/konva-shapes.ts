import Konva from 'konva';

/**
 * Konva 10 exports its classes from one default object, so this file re-exports them by name.
 * Each name is both the class (a value) and its type.
 */
export const Arrow = Konva.Arrow;
export const Circle = Konva.Circle;
export const Group = Konva.Group;
export const Layer = Konva.Layer;
export const Line = Konva.Line;
export const Rect = Konva.Rect;
export const Stage = Konva.Stage;
export const Text = Konva.Text;

export type Arrow = Konva.Arrow;
export type Circle = Konva.Circle;
export type Group = Konva.Group;
export type Layer = Konva.Layer;
export type Line = Konva.Line;
export type Rect = Konva.Rect;
export type Stage = Konva.Stage;
export type Text = Konva.Text;
export type KonvaShape = Konva.Shape;
